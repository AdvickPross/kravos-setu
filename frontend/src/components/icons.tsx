/** Section icon by brief section title. Unknown titles fall back to a file. */
export function SectionIcon({ title, ...p }: IconProps & { title: string }) {
  switch (title) {
    case "Allergies":
      return <ShieldIcon {...p} />;
    case "Medications":
      return <PillIcon {...p} />;
    case "Conditions":
      return <HeartPulseIcon {...p} />;
    case "Labs":
      return <FlaskIcon {...p} />;
    case "Vitals":
      return <ActivityIcon {...p} />;
    case "Procedures":
      return <ClipboardIcon {...p} />;
    case "Immunizations":
      return <SyringeIcon {...p} />;
    default:
      return <FileIcon {...p} />;
  }
}
